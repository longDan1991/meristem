/**
 * 一次执行：**手伸出去就一定是作业**。
 *
 * 立即结束的执行（读一个文件、`echo`）= 一个**已经结束**的作业；还没回来的执行（`cargo test`、
 * 远端 MCP 调用）= 一个**还在跑**的作业。**模型侧看不见这个区别** —— 工具的 schema、描述、
 * 它要写的参数一个字都不改。判据是"这次执行"，不是"这只手"：同一个 `bash` 手，跑 `echo hi`
 * 是立刻结束，跑 `cargo test` 是还在跑 —— 动手之前谁都算不出来，所以这个判断只存在于这里：
 * **这个 `Job` 结束了没有**（DESIGN §9）。
 *
 * 它是**句柄 + 几条事实**（id / space / at / name）：界面与 `job_list` 靠这几条就说得清
 * "有什么在跑、在哪、多久了"，不必去别处打听。
 *
 * 四个面向里，这里声明的是**手**与**模型**看得到的那两面：
 *   · 手（实现者）：用 `base.ts` 的两个原语（`settled` / `background`）把执行起起来，
 *     结束时给一句交代；不碰线、不碰模型、不碰界面。
 *   · 模型（消费者）：`report()` 是"现在怎么样"，它会被**拼进消息内容**（作业 id 也在里面），
 *     模型靠这个 id 把前后两条消息对上（配对是模型的事，不是程序的事，DESIGN §9.6）；
 *     `output()` 是原样的输出（**不等于最终交代**：交代在结束时才落地）。
 *
 * 状态只有两个：**在跑 / 结束**。失败与"被人取消"都是**交代**（`report()` 的文本），
 * 不是需要分类的状态 —— 错误也是交代，不是 `error` 态。
 */
export interface Job {
  /** 稳定名字（底座给）：消息内容里用它、`job_output(id)` / `job_cancel(id)`、界面引用它都用它。 */
  readonly id: string;

  /**
   * 这次执行在哪个**空间**里：由树在调用那只手的时候给（当前实现就是节点 id）。
   * 同一个空间里的作业互相看得见（`table.ts` 按它筛），不同空间互不打扰。
   */
  readonly space: string;

  /** 起于什么时候（时间戳）：进度句与界面上的"已跑多久"都从它算。 */
  readonly at: number;

  /** 哪只手起的（进进度句与消息内容里的那行）。 */
  readonly name: string;

  /**
   * **用这一手自己的话说"我现在怎么样"**：
   *   · 还在跑 → 由底座的默认实现按事实说（作业 #id、名字、已跑多久、吐了多少）；
   *   · 结束 → 手写的那句交代（结果 / 失败 / "被人取消了"）。
   *
   * 这是作业文本的**唯一出口**：harness 一个字的文本都不拼 —— 它只把这句放进消息内容里
   * （起手时一条、结束时一条，见 DESIGN §9.5）。每一句都带 `作业 #id（名字）：` 那一行，
   * 起手与结束两条就靠它配对（匹配的事归模型，§9.6）。
   */
  report(): string;

  /**
   * 现在吐了什么（**原文：不裁剪、不折叠**）：给人看进度，也给 `job_output` 用。
   * 压缩不在这里 —— 要折叠是**发送边界**那一层的事，裁掉多少、怎么取回由它自己说清（§5.6）。
   */
  output(): string;

  /**
   * 吐了多少字（总数）：它是"它在动还是卡住了"的唯一判据，`report()` / `job_list` / 界面都用它。
   * 留着它是因为进度句每轮都要问 —— 让它们去量 `output()` 的长度，就得把整个输出拼一遍。
   */
  produced(): number;

  /**
   * **跟着这块输出走**：先把已经吐出来的按顺序给一遍，之后有新块就给新块，作业一结束就收。
   *
   * 界面那张手卡片就是靠它画的（每次调用各给一个自己的游标，互相不打扰）—— 所以**没有"进度事件"**
   * 这回事，树里也不用装时钟。它给的是原文（不裁剪、不折叠），也**不阻塞谁**：遍历慢的只是自己慢。
   */
  stream(): AsyncIterable<string>;

  /** 取消：结局仍是一条交代（"被人取消了"），不是特殊状态。 */
  cancel(): void;

  /** 等它结束（幂等）；结束后 `report()` 就是交代。 */
  wait(): Promise<void>;
}

/**
 * 底座造作业需要的事实：在哪个空间、哪只手起的（`id` / `at` 由底座自己给）。
 *
 * `space` 从 `HandContext.space` 抄过来 —— 树在调用这只手的时候给的那个名字。
 */
export interface JobFacts {
  readonly space: string;
  readonly name: string;
}
